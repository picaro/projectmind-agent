/**
 * Forced screenshot/video/trace capture for continuous test runs.
 *
 * Playwright has no CLI flags for screenshot or video, so the agent writes a
 * small config next to the project's own `playwright.config.*` (inside the
 * throwaway run worktree) that spreads the project config and overrides `use`
 * at the top level and in every project. Paths in the project config resolve
 * against the config file's directory, which the wrapper shares, so nothing
 * else changes. Only allowlisted enum values are written into the file.
 */
import fs from "node:fs";
import path from "node:path";
import {
  CONTINUOUS_TEST_SCREENSHOT_MODES,
  CONTINUOUS_TEST_TRACE_MODES,
  CONTINUOUS_TEST_VIDEO_MODES,
  type ContinuousTestCapture,
} from "./improvement-contracts/continuous-test-job.js";

/** Playwright's own lookup order for a config in the working directory. */
export const PLAYWRIGHT_CONFIG_NAMES = [
  "playwright.config.ts",
  "playwright.config.js",
  "playwright.config.mts",
  "playwright.config.mjs",
  "playwright.config.cts",
  "playwright.config.cjs",
] as const;

export const CAPTURE_WRAPPER_BASENAME = "playwright.projectmind.config";

export function findPlaywrightConfig(dir: string): string | null {
  for (const name of PLAYWRIGHT_CONFIG_NAMES) {
    const candidate = path.join(dir, name);
    try {
      if (fs.statSync(candidate).isFile()) return candidate;
    } catch {
      // not there
    }
  }
  return null;
}

function assertAllowed(capture: ContinuousTestCapture): ContinuousTestCapture {
  if (
    !(CONTINUOUS_TEST_SCREENSHOT_MODES as readonly string[]).includes(capture.screenshot) ||
    !(CONTINUOUS_TEST_VIDEO_MODES as readonly string[]).includes(capture.video) ||
    !(CONTINUOUS_TEST_TRACE_MODES as readonly string[]).includes(capture.trace)
  ) {
    throw new Error("capture mode outside the allowlist");
  }
  return { screenshot: capture.screenshot, video: capture.video, trace: capture.trace };
}

/** Source of the wrapper config for `baseConfigPath`. */
export function captureWrapperSource(baseConfigPath: string, capture: ContinuousTestCapture): string {
  const ext = path.extname(baseConfigPath);
  const overrides = JSON.stringify(assertAllowed(capture));
  const baseImport = JSON.stringify(`./${path.basename(baseConfigPath)}`);
  const body = [
    `const overrides = ${overrides};`,
    "const withCapture = (use) => ({ ...(use ?? {}), ...overrides });",
    "const config = { ...base, use: withCapture(base.use) };",
    "if (Array.isArray(base.projects)) {",
    "  config.projects = base.projects.map((project) => ({ ...project, use: withCapture(project.use) }));",
    "}",
  ];
  const header = "// Generated by projectmind-agent for one continuous test run; never committed.";
  if (ext === ".cjs" || ext === ".cts") {
    return [
      header,
      `const loaded = require(${baseImport});`,
      "const base = loaded && loaded.__esModule ? loaded.default : loaded;",
      ...body,
      "module.exports = config;",
      "",
    ].join("\n");
  }
  const typescript = ext === ".ts" || ext === ".mts";
  return [
    header,
    ...(typescript ? ["// @ts-nocheck"] : []),
    `import loaded from ${baseImport};`,
    `const base = loaded?.default ?? loaded;`,
    ...body,
    "export default config;",
    "",
  ].join("\n");
}

/** Write the wrapper next to the base config; returns its path. */
export function writeCaptureWrapper(baseConfigPath: string, capture: ContinuousTestCapture): string {
  const wrapper = path.join(
    path.dirname(baseConfigPath),
    `${CAPTURE_WRAPPER_BASENAME}${path.extname(baseConfigPath)}`,
  );
  fs.writeFileSync(wrapper, captureWrapperSource(baseConfigPath, capture), { mode: 0o644 });
  return wrapper;
}

export function argvHasConfig(argv: readonly string[]): boolean {
  return argv.some((a) => a === "--config" || a === "-c" || a.startsWith("--config="));
}

/** The run's argv with `--config <wrapper>` (unchanged when it already names a config). */
export function captureArgv(argv: readonly string[], wrapperPath: string): string[] {
  if (argvHasConfig(argv)) return [...argv];
  return [...argv, "--config", wrapperPath];
}

/** Same invocation, but only listing tests: proves the wrapper loads before the real run. */
export function listArgv(argv: readonly string[]): string[] {
  const out = argv.filter((a) => !a.startsWith("--reporter"));
  return [...out, "--list", "--reporter=list"];
}
